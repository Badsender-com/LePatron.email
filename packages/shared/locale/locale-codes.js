const languages = new Set(LANGUAGE_CODES);
const countries = new Set(COUNTRY_CODES);
const LOCALE_PATTERN = /^([a-z]{2})(?:-([a-z]{2}))?$/i;

/**
 * A code as the role's list writes it (`fr`, `BE`, `fr-BE`), whatever case it
 * came in, or null when the list does not hold it.
 *
 * @param {string} role `language`, `country` or `locale`
 * @param {*} raw
 * @returns {string|null}
 */
function normaliseCode(role, raw) {
  if (typeof raw !== 'string') return null;
  const code = raw.trim();
  if (role === 'language') {
    const language = code.toLowerCase();
    return languages.has(language) ? language : null;
  }
  if (role === 'country') {
    const country = code.toUpperCase();
    return countries.has(country) ? country : null;
  }
  if (role === 'locale') {
    const match = LOCALE_PATTERN.exec(code);
    if (!match) return null;
    const language = normaliseCode('language', match[1]);
    const country = match[2] ? normaliseCode('country', match[2]) : null;
    // A country asked for and not found is no locale, not the language alone.
    if (match[2] && !country) return null;
    return joinLocale({ language, country });
  }
  return null;
}

/**
 * @param {string|null} locale `fr-BE`, `fr` or null
 * @returns {{language: (string|null), country: (string|null)}}
 */
function splitLocale(locale) {
  const match = typeof locale === 'string' ? LOCALE_PATTERN.exec(locale) : null;
  if (!match) return { language: null, country: null };
  return {
    language: match[1].toLowerCase(),
    country: match[2] ? match[2].toUpperCase() : null,
  };
}

/**
 * @param {Object} parts
 * @param {string|null} parts.language
 * @param {string|null} parts.country
 * @returns {string|null} `fr-BE`, `fr`, or null without a language
 */
function joinLocale({ language, country }) {
  if (!language) return null;
  return country ? `${language}-${country}` : language;
}

/**
 * The locale of an email from the codes of the values it carries, one per
 * role: a `locale` code decides alone; otherwise the language and the country
 * compose. A missing part is null, never guessed.
 *
 * @param {Object} codes
 * @param {string|null} [codes.locale]
 * @param {string|null} [codes.language]
 * @param {string|null} [codes.country]
 * @returns {{language: (string|null), country: (string|null), locale: (string|null)}}
 */
function composeLocale({ locale = null, language = null, country = null }) {
  if (locale) {
    const parts = splitLocale(locale);
    return { ...parts, locale: joinLocale(parts) };
  }
  return {
    language: language || null,
    country: country || null,
    locale: joinLocale({ language, country }),
  };
}

