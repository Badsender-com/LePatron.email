'use strict';

// Compiles ONE component into the file that gets committed.
//
// Split from the command line script so the golden test can call it in-process
// and compare strings, rather than shell out and read an exit code. Why the
// build step exists at all is told at the top of
// scripts/compile-block-builder-components.js.

const fs = require('fs');
const path = require('path');
const { parse, compileScript } = require('@vue/compiler-sfc');

const {
  compileTemplate,
} = require('../../packages/shared/block-builder/template.js');
const {
  stripComments,
  inlineStyles,
  substitutePlaceholders,
} = require('./markup-pipeline.js');
const { compileRender, renderWithSentinels } = require('./render-component.js');
const { checkManifest, checkPropsDeclared } = require('./component-checks.js');

const COMPONENTS_DIR = path.join(
  __dirname,
  '..',
  '..',
  'packages',
  'shared',
  'block-builder',
  'components'
);

/**
 * @param {string} name e.g. `button`
 * @param {string} source the `.vue` file
 * @param {Object} manifest what its `.slots.js` exports
 * @returns {{ssrRender: Function, slots: Object, variants: Object}}
 */
function loadComponent(name, source, manifest) {
  const { descriptor, errors } = parse(source, { filename: `${name}.vue` });
  if (errors.length) {
    throw new Error(
      `${name}.vue does not parse:\n${errors
        .map((e) => `  ${e.message}`)
        .join('\n')}`
    );
  }
  if (!descriptor.template) {
    throw new Error(`${name}.vue has no <template>.`);
  }

  const { slots, variants } = checkManifest(name, manifest);
  const bindings = descriptor.scriptSetup
    ? compileScript(descriptor, { id: name }).bindings || {}
    : {};
  checkPropsDeclared(name, bindings, slots, variants);

  const { ssrRender } = compileRender(
    name,
    descriptor.template.content,
    bindings
  );
  return { ssrRender, slots, variants };
}

/**
 * One variant, from the component to the placeholder source.
 *
 * @returns {Promise<{html: string, used: Array<string>}>}
 */
async function compileVariant(name, component, variant) {
  const rendered = await renderWithSentinels(
    component,
    component.variants[variant]
  );
  const inlined = await inlineStyles(stripComments(rendered));
  const { html, used } = substitutePlaceholders(
    inlined,
    component.slots,
    `${name} (${variant})`
  );

  // Compiled by the real engine before being written. It is the engine that
  // knows which contexts exist, and it throws on one it does not — so an
  // unknown context fails the build here rather than shipping a template the
  // editor cannot render. The invariant is checked too, since everything
  // downstream relies on it.
  const compiled = compileTemplate(html);
  if (compiled.chunks.length !== compiled.slots.length + 1) {
    throw new Error(`${name} (${variant}): compiled template is inconsistent.`);
  }

  return { html, used };
}

/**
 * A slot missing from ONE variant is normal — an image with no link does not
 * render an `href`. A slot missing from EVERY variant is a dead entry.
 */
function assertEverySlotRendered(name, slots, everUsed) {
  const dead = Object.keys(slots).filter((slot) => !everUsed.has(slot));
  if (dead.length) {
    throw new Error(
      `${name}.slots.js declares ${dead.map((d) => `"${d}"`).join(', ')}, ` +
        'which no variant renders. Use them or drop them.'
    );
  }
}

/**
 * @param {{name: string, source: string, manifest: Object}} input
 * @returns {Promise<Object<string, string>>} variant name -> placeholder source
 */
async function compileSource({ name, source, manifest }) {
  const component = loadComponent(name, source, manifest);
  const templates = {};
  const everUsed = new Set();

  for (const variant of Object.keys(component.variants)) {
    // eslint-disable-next-line no-await-in-loop
    const { html, used } = await compileVariant(name, component, variant);
    used.forEach((slot) => everUsed.add(slot));
    templates[variant] = html;
  }

  assertEverySlotRendered(name, component.slots, everUsed);
  return templates;
}

const banner = (name) =>
  [
    '// Generated by scripts/compile-block-builder-components.js — do not edit.',
    `// Source: packages/shared/block-builder/components/${name}.vue`,
    '//',
    '// Editing this file by hand is caught by the golden test: it recompiles',
    '// the component and fails on any difference.',
    "'use strict';",
    '',
  ].join('\n');

/**
 * What `<name>.compiled.js` must contain.
 *
 * Always an object keyed by variant — `default` when the component has none —
 * so every caller reads it the same way.
 *
 * @param {string} name
 * @param {string} [dir]
 * @returns {Promise<string>}
 */
async function compileComponent(name, dir = COMPONENTS_DIR) {
  const source = fs.readFileSync(path.join(dir, `${name}.vue`), 'utf8');
  // eslint-disable-next-line import/no-dynamic-require, global-require
  const manifest = require(path.join(dir, `${name}.slots.js`));

  const templates = await compileSource({ name, source, manifest });
  return `${banner(name)}module.exports = ${JSON.stringify(
    templates,
    null,
    2
  )};\n`;
}

/**
 * @param {string} [dir]
 * @returns {Array<string>} the component names, sorted
 */
function listComponents(dir = COMPONENTS_DIR) {
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith('.vue'))
    .map((file) => path.basename(file, '.vue'))
    .sort();
}

module.exports = {
  COMPONENTS_DIR,
  compileSource,
  compileComponent,
  listComponents,
};
